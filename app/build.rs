//! Generates keycode tables from the vendored vial-qmk hjson files and the
//! vial-gui `keycodes_v6.py` name table (see `data/keycodes/SOURCE.md`).
//!
//! The hjson files are incremental: they are merged by version, following the
//! same rules as QMK's `lib/python/qmk/keycodes.py` (`!delete!` removes a key,
//! `!reset!` inside a list discards the previously merged items).

use serde_json::{Map, Value};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let data = Path::new("data/keycodes");
    println!("cargo:rerun-if-changed=data/keycodes");

    let spec = load_qmk_spec(data);
    let vial = load_vial_names(&data.join("vial_keycodes_v6.py"));

    let mut out = String::new();
    out.push_str("// @generated by build.rs from data/keycodes. Do not edit.\n\n");
    write_qmk_tables(&mut out, &spec);
    write_vial_table(&mut out, &vial);

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("keycodes_generated.rs");
    fs::write(dest, out).expect("write generated keycodes");
}

fn version_key(v: &str) -> Vec<u32> {
    v.split('.').map(|p| p.parse().unwrap_or(0)).collect()
}

fn load_qmk_spec(dir: &Path) -> Map<String, Value> {
    // (version, is_group_file, file name)
    let mut files: Vec<(Vec<u32>, bool, String)> = Vec::new();
    for entry in fs::read_dir(dir).expect("read data/keycodes") {
        let name = entry.unwrap().file_name().into_string().unwrap();
        let Some(stem) = name.strip_prefix("keycodes_").and_then(|s| s.strip_suffix(".hjson")) else {
            continue;
        };
        let (version, group) = match stem.split_once('_') {
            Some((v, _)) => (v, true),
            None => (stem, false),
        };
        if !version.starts_with(|c: char| c.is_ascii_digit()) {
            continue;
        }
        files.push((version_key(version), group, name));
    }
    files.sort();

    let mut spec = Map::new();
    for (_, _, name) in files {
        let text = fs::read_to_string(dir.join(&name)).unwrap();
        if text.trim().is_empty() {
            continue; // some versions only exist as empty placeholders
        }
        let value: Value = deser_hjson::from_str(&text).unwrap_or_else(|e| panic!("{name}: {e}"));
        if let Value::Object(obj) = value {
            merge(&mut spec, obj);
        }
    }
    spec
}

fn merge(target: &mut Map<String, Value>, source: Map<String, Value>) {
    for (key, value) in source {
        match value {
            Value::String(s) if s == "!delete!" => {
                target.remove(&key);
            }
            Value::Object(obj) => match target.get_mut(&key) {
                Some(Value::Object(existing)) => merge(existing, obj),
                _ => {
                    let mut fresh = Map::new();
                    merge(&mut fresh, obj);
                    target.insert(key, Value::Object(fresh));
                }
            },
            Value::Array(items) => {
                let reset = items.iter().any(|v| v == "!reset!");
                let items: Vec<Value> = items.into_iter().filter(|v| v != "!reset!").collect();
                match target.get_mut(&key) {
                    Some(Value::Array(existing)) if !reset => existing.extend(items),
                    _ => {
                        target.insert(key, Value::Array(items));
                    }
                }
            }
            other => {
                target.insert(key, other);
            }
        }
    }
}

fn parse_hex(s: &str) -> Option<u32> {
    u32::from_str_radix(s.trim().trim_start_matches("0x").trim_start_matches("0X"), 16).ok()
}

fn write_qmk_tables(out: &mut String, spec: &Map<String, Value>) {
    let mut keycodes: Vec<(u32, String, String, Vec<String>)> = Vec::new();
    if let Some(Value::Object(kcs)) = spec.get("keycodes") {
        for (code, def) in kcs {
            let Some(code) = parse_hex(code) else { continue };
            let Some(key) = def.get("key").and_then(Value::as_str) else { continue };
            let label = def.get("label").and_then(Value::as_str).unwrap_or("").to_string();
            let aliases = def
                .get("aliases")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(Value::as_str).map(str::to_string).collect())
                .unwrap_or_default();
            keycodes.push((code, key.to_string(), label, aliases));
        }
    }
    keycodes.sort_by_key(|k| k.0);

    out.push_str("/// QMK keycodes: (code, key, label, aliases), sorted by code.\n");
    out.push_str("pub static QMK_KEYCODES: &[(u16, &str, &str, &[&str])] = &[\n");
    for (code, key, label, aliases) in &keycodes {
        let _ = writeln!(out, "    ({code:#06x}, {key:?}, {label:?}, &{aliases:?}),");
    }
    out.push_str("];\n\n");

    let mut ranges: Vec<(u32, u32, String)> = Vec::new();
    if let Some(Value::Object(rs)) = spec.get("ranges") {
        for (range, def) in rs {
            let Some((start, size)) = range.split_once('/') else { continue };
            let (Some(start), Some(size)) = (parse_hex(start), parse_hex(size)) else { continue };
            let Some(define) = def.get("define").and_then(Value::as_str) else { continue };
            ranges.push((start, size, define.to_string()));
        }
    }
    ranges.sort();
    out.push_str("/// QMK keycode ranges: (start, size - 1, define), sorted by start.\n");
    out.push_str("#[allow(dead_code)] // checked against the decoder constants in tests\n");
    out.push_str("pub static QMK_RANGES: &[(u16, u16, &str)] = &[\n");
    for (start, size, define) in &ranges {
        let _ = writeln!(out, "    ({start:#06x}, {size:#06x}, {define:?}),");
    }
    out.push_str("];\n\n");
}

/// Reads the `"NAME": value,` entries of the `kc = { ... }` dict in vial-gui's
/// `keycodes_v6.py`. The loops that follow the dict (MO(x), USERxx, ...) are
/// handled in code by `vial::names`.
fn load_vial_names(path: &Path) -> Vec<(String, u32)> {
    let text = fs::read_to_string(path).expect("read vial_keycodes_v6.py");
    let mut names = Vec::new();
    let mut inside = false;
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with("kc = {") {
            inside = true;
            continue;
        }
        if !inside {
            continue;
        }
        if t.starts_with('}') {
            break;
        }
        let Some(rest) = t.strip_prefix('"') else { continue };
        let Some((name, value)) = rest.split_once("\":") else { continue };
        let value = value.trim().trim_end_matches(',').trim();
        let parsed = if let Some(hex) = value.strip_prefix("0x").or_else(|| value.strip_prefix("0X")) {
            u32::from_str_radix(hex, 16).ok()
        } else {
            value.parse().ok()
        };
        if let Some(v) = parsed {
            names.push((name.to_string(), v));
        }
    }
    assert!(names.len() > 400, "vial keycode table looks truncated ({} entries)", names.len());
    names
}

fn write_vial_table(out: &mut String, names: &[(String, u32)]) {
    out.push_str("/// vial-gui (protocol 6) keycode names as used in `.vil` files.\n");
    out.push_str("pub static VIAL_NAMES: &[(&str, u16)] = &[\n");
    for (name, value) in names {
        let _ = writeln!(out, "    ({name:?}, {value:#06x}),");
    }
    out.push_str("];\n");
}
